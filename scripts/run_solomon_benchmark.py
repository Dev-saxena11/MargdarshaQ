"""
run_solomon_benchmark.py
-------------------------
Measure this project's solvers against Solomon's published best-known CVRPTW
solutions.

Everything else in this repo compares QPSO to baselines written here, on
instances generated here. This compares it to results the field already agrees
on, which is the only way to answer "is any of this any good" rather than
"which of ours is best".

Run with:

    python scripts/run_solomon_benchmark.py                       # every shipped instance
    python scripts/run_solomon_benchmark.py --instances R101 C101
    python scripts/run_solomon_benchmark.py --max-iter 400        # a longer search
    python scripts/run_solomon_benchmark.py --algorithms QPSO "Greedy NN"

Be aware of the cost: these are 100-customer instances, and a single QPSO run
at --max-iter 200 takes roughly a minute and a half. The full six-instance,
five-algorithm sweep is therefore tens of minutes, not seconds. Start with
--instances R101 while you are checking something.

Results are written to data/solomon_results.md unless --no-report is given.
"""

from __future__ import annotations

import argparse
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core.benchmark_solomon import SOLVERS, print_table, run_suite  # noqa: E402
from app.core.solomon import available_instances, best_known  # noqa: E402

REPORT_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data", "solomon_results.md",
)


def write_report(runs, path, max_iter, seed):
    by_instance = {}
    for run in runs:
        by_instance.setdefault(run.instance, []).append(run)

    lines = [
        "# Solomon CVRPTW benchmark results",
        "",
        f"_Generated by `scripts/run_solomon_benchmark.py` on "
        f"{datetime.date.today().isoformat()} with `--max-iter {max_iter} --seed {seed}`. "
        f"Re-run it to reproduce every figure below._",
        "",
        "Solomon's objective is hierarchical: fewest vehicles first, then shortest "
        "distance. A solution using more vehicles does not beat one using fewer, "
        "however short its routes are -- so the vehicle count is reported beside the "
        "distance rather than behind it.",
        "",
        "A run that breaks a time window has no gap to report. Every published figure "
        "is feasible, and an infeasible solution is usually short *because* it skipped "
        "a window, so quoting its distance as a result would be backwards.",
        "",
    ]

    for instance, rows in by_instance.items():
        known = best_known(instance)
        known_text = (f"{known[0]} vehicles, distance {known[1]:.2f}"
                      if known else "not recorded")
        lines += [
            f"## {instance}",
            "",
            f"Best known: **{known_text}**",
            "",
            "| Algorithm | Feasible | Vehicles | vs best known | Distance | Gap | Runtime (s) |",
            "| :--- | :--- | ---: | ---: | ---: | ---: | ---: |",
        ]
        for r in sorted(rows, key=lambda r: (not r.feasible, r.distance)):
            gap = "--" if r.distance_gap_pct is None else f"{r.distance_gap_pct:+.2f}%"
            extra = "--" if r.extra_vehicles is None else f"{r.extra_vehicles:+d}"
            feas = "yes" if r.feasible else "**NO**"
            lines.append(
                f"| {r.algorithm} | {feas} | {r.vehicles_used} | {extra} | "
                f"{r.distance:.2f} | {gap} | {r.runtime_sec:.2f} |"
            )
        lines.append("")

    infeasible = [r for r in runs if not r.feasible]
    if infeasible:
        lines += [
            f"> {len(infeasible)} of {len(runs)} runs were infeasible and are shown "
            f"without a gap. They are not results that happen to be worse.",
            "",
        ]

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"\nReport written to {path}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instances", nargs="*", default=None,
                        help=f"default: all shipped ({', '.join(available_instances())})")
    parser.add_argument("--algorithms", nargs="*", default=None,
                        help=f"default: all ({', '.join(SOLVERS)})")
    parser.add_argument("--max-iter", type=int, default=200)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--no-report", action="store_true",
                        help="print the table but do not write data/solomon_results.md")
    args = parser.parse_args()

    for name in args.algorithms or []:
        if name not in SOLVERS:
            parser.error(f"unknown algorithm {name!r}; choose from {', '.join(SOLVERS)}")

    runs = run_suite(instances=args.instances, algorithms=args.algorithms,
                     max_iter=args.max_iter, seed=args.seed)
    print_table(runs)
    if not args.no_report:
        write_report(runs, REPORT_PATH, args.max_iter, args.seed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
